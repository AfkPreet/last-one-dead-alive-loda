function glyph(ch) { return G[ch] || G[ch.toUpperCase()] || G['?']; }

/** Measure a string in pixels at the given scale + letter spacing. */
function measure(text, scale, spacing) {
  spacing = spacing === undefined ? 1 : spacing;
  return text.length * (5 + spacing) * scale - spacing * scale;
}

/** Draw text onto a tools/png.js Surface. align: 'left' | 'center' | 'right'. */
function draw(surf, text, x, y, scale, hex, opts) {
  opts = opts || {};
  const spacing = opts.spacing === undefined ? 1 : opts.spacing;
  const alpha = opts.alpha === undefined ? 1 : opts.alpha;
  const w = measure(text, scale, spacing);
  let cx = x;
  if (opts.align === 'center') cx = x - w / 2;
  else if (opts.align === 'right') cx = x - w;
  for (const ch of text) {
    const rows = glyph(ch).split(' ');
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < 5; c++) {
        if (rows[r][c] === '1') {
          surf.rect(cx + c * scale, y + r * scale, scale, scale, hex, alpha);
        }
      }
    }
    cx += (5 + spacing) * scale;
  }
  return w;
}

module.exports = { draw, measure };
